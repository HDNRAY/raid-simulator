/**
 * Boss 的血量 —— **单独一个文件，因为它不属于"刻度"也不属于"招式"**。
 *
 * ------------------------------------------------------------------
 * 这个数字是怎么定出来的（不是拍脑袋）
 * ------------------------------------------------------------------
 *
 * 拿引擎实测两个数：
 *
 *   Boss 承伤 DPS：玩家完全不还手时，Boss 用 15.1 秒把玩家 1000 血打光
 *                 → **66 内部伤害/秒**（含蓄能增伤）
 *   玩家输出 DPS：只用「攻」时 2.14 次/秒 × 10 伤害
 *                 → **214 内部伤害/秒**
 *
 * 玩家输出是 Boss 的 3.2 倍，所以如果双方血量都是 1000，
 * 玩家 4.7 秒就能赢 —— 防御技能完全没有存在意义（实测就是这样）。
 *
 * 目标：让"必须用防御技能"成为通关条件。
 * 取 12 秒左右的战斗长度（略短于玩家被打死所需的 15.1 秒，
 * 但差距要小到"挨满三发重击就会翻车"）：
 *
 *   2400 / 214 ≈ 11.2 秒   ← Boss 被击杀所需
 *   1000 /  66 ≈ 15.1 秒   ← 玩家被打死所需
 *
 * 两者的差距就是"容错空间"：不躲不挡大约会挨 740 伤害，
 * 也就是**能赢但只剩两成血**；多挨一发重击（300）就必输。
 * 于是防御技能不再是"锦上添花"而是通关条件：
 *   - 「防」减伤 40% 把承伤 DPS 压到 40 → 玩家可活 25 秒
 *   - 「闪」直接免掉一次重击（300 伤害 = 全血的 30%）
 *   - 「破」打断蓄能，等于免掉后面 10 秒的 30% 增伤
 *
 * 这三条正好对应 Boss 的三个招式，所以"看前摇做反应"是通关的核心。
 */
