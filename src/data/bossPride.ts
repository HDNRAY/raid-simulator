/**
 * **「傲慢」** —— 第一个 Boss「伪名一郎」的改造（快慢刀 + 霸体合并）。
 *
 * ==================================================================
 * 它和另外两个 Boss 的区别是**题型**，不是数值
 * ==================================================================
 *
 * 设计定位（`docs/specs/2026-10-11-pride-boss.md` §1.1）：
 *
 *   傲慢   → "**这一下发不发得起 30 炁去躲？躲不掉的那一下，
 *              我留了什么给它？**"（防御资源本身）
 *   色欲   → "**我现在该不该继续打？**"（反伤 + 3 秒锁死惩罚贪刀）
 *
 * ------------------------------------------------------------------
 * 快慢刀：三招 = 三条通道（本设计的核心）
 * ------------------------------------------------------------------
 *
 * | 刀 | 读条 | 伤害 | 通道 | 正确应对 |
 * |---|---|---|---|---|
 * | 轻蔑 | 1.0s | 20 | 炁的税 | 硬吃（20 = 1/5 血），把炁留给别的刀 |
 * | 呵斥 | 1.5s | 40 | 「破」的靶子 | 打断；没破就闪 / 挡 |
 * | 碾压 | 2.0s | 60 | 只能闪 | 闪避（挡只剩 25% 收益，破完全无效） |
 *
 * 三个名字构成「**眼 → 口 → 手**」的递进 —— 轻蔑（不屑）→ 呵斥（出声）
 * → 碾压（动手），即"他越来越愿意搭理你"。命名理由写在 `zh-CN.ts` 的
 * `boss` 域里。
 *
 * ⚠️ **为什么三招必须走三条通道**（设计 §1.2）：读条 UI 只给"剩余秒数"，
 * 玩家要先把"条有多长"读成"这是哪一刀"。1.0 秒里走不完
 * "观察 → 判断 → 按键"，所以快刀的定位是**资源税**而不是反应测试。
 *
 * ⚠️ **勘误（实测推翻了设计 §3.1）**：读条 UI 是**固定 600px 宽**的
 * CastBar（`ui/layout.ts` 的 `castBar.w`），填充按 `progress` 走 ——
 * **条的总长根本不随读条时长变化**，所以"1.0 与 1.5 的条在画面上看得出
 * 长短差别"**不成立**（已实机截图验收）。玩家真正能用的线索是：
 *   ① **剩余秒数数字**（`1.0` / `1.5` / `2.0`）—— 最可靠
 *   ② **填充速度**（1.0s 的条涨得快一倍）
 *   ③ 青蓝 vs 青绿（只区分霸体，区分不了 20 与 40）
 * 快慢刀仍然成立，但线索是"**秒数 + 填充速度**"，不是"条的长度"。
 *
 * ------------------------------------------------------------------
 * 随机释放：它不是手感加分项，是三个技能能否共存的前提
 * ------------------------------------------------------------------
 *
 * 三者冷却相同（3s），而旧的顺序轮转是"取第一个可用的" ——
 * 于是**永远只有 steps[0] 那一个技能会放出来**，另外两个是死内容
 * （设计 §4.1）。所以这里用的是 `weightedRotation`。
 *
 * ⚠️ `gapMs`（**4000**）**比冷却长得多**（4000 > 3000），所以真正决定
 * 节奏的是 `gapMs` 而不是冷却 —— 三者冷却写得一样是刻意的（设计 §2），
 * 难度旋钮只有 `gapMs` 一个。
 * ⚠️ 标定过程（以及一度误推到 16000 的错误诊断）写在下面的 `gapMs`
 * 定义处，不要只看这一行。
 */

