/**
 * 前摇标记的**公共字段**（不含时长）。
 *
 * ⚠️ 时长必须**等于所挂技能自己的 `castTime`**，所以每个技能各有一份。
 *
 * 设计 §6.5 第 1 条记录了这个既有问题：原先只有一个写死 3.0 秒的
 * `BOSS_TELEGRAPH`，比本设计的三个读条都长 —— 它 `hidden: true`
 * （UI 不显示），但语义上是错的（"前摇标记"应当在前摇结束时消失）。
 * 三个读条各不相同之后，一个固定时长**不可能**对三招都正确，
 * 所以这里顺手把它拆成四份（含「回补」）。
 */
function telegraphFor(skillId: string, duration: number): BuffDef {
  return {
    id: `${skillId}-telegraph`,
    nameKey: 'hud.casting',
    icon: 'telegraph',
    polarity: 'neutral',
    color: C.boss,
    duration,
    maxStacks: 1,
    stacking: { mode: 'refresh' },
    hidden: true,
  };
}

