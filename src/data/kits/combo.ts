/**
 * 「击」以及它的**派生窗口** —— 派生系技能。
 *
 * ==================================================================
 * 为什么单独一个文件
 * ==================================================================
 *
 * `data/content.ts` 顶到了 700 行上限（AGENTS.md §3）。这一块是**内聚的
 * 一小撮**：`COMBO_WINDOW`（派生窗口 buff）与 `STRIKE`（派生技「击」）——
 * 两者互相引用（击的 `requires` 认的就是这个 buff），且与基础技能没有交集。
 *
 * ⚠️ 这两个块**必须放同一个文件**：把 `COMBO_WINDOW` 留在 `content.ts`
 * 而把 `STRIKE` 放这里，就会造出 `content ↔ kits/combo` 的**循环引用**
 * （本仓库在 `data/scale.ts` 上踩过一次，那种错误表现为"某个 import
 * 是 undefined"，很难查）。
 *
 * ==================================================================
 * ⚠️ 当前状态：「击」**没有产出者**（这是预期的，不是 bug）
 * ==================================================================
 *
 * 2026-10-12 用户定的："**当前的截本身就能派生击，这个我们放到 p3
 * 或者初始化炁机的地方再实现，把现在的截的派生去掉。**"
 *
 * 所以：
 *   - 「截」成功后**不再**挂 `combo-window`（那一段已删）
 *   - 但「击」与 `combo-window` **都保留** —— P3 由炁机重新接上
 *   - 于是**今天没有任何东西会开这个窗口**，所以「击」永远不可用
 *
 * 按 `AGENTS.md` §2 的判据，这是"**未实现：设计过、引擎还没有消费者**"
 * → **保留 + 标注**（就是这一段），并让它的后果**可被机器检查**：
 * `tests/unit/playerKits.test.ts` 里有一条断言专门钉住"现在没有产出者"，
 * 免得下一个人以为是 bug 而"顺手删掉"或"顺手修好"。
 *
 * ⚠️ **为什么不能靠"ui 里看不到"来判断**：`deriveSlots` 只在窗口开着时
 * 才把派生技插进技能栏，所以它在界面上**完全不存在** —— 这正是需要
 * 一条测试来记住"它还在、而且是有意留着的"的原因。
 */

import { logicMs } from '../../core/loopConstants';
import type { BuffDef, SkillDef } from '../../core/types';
import type { SkillId } from '../../core/types/ids';
import { C, S } from '../scale';
import { DODGE_CHARGE } from './dodgeCharge';

/**
 * 「派生窗口」：**只有这个 buff 在时，派生技能才会被激活**。
 *
 * ==================================================================
 * ⚠️ 「派生」与「限制」是两种机制（用户强调过）
 * ==================================================================
 *
 *   派生（本 buff + 技能的 `requires`）— **正向、激活**、**单技**
 *     "只有这个 buff 在时，这个技能才被激活"（平时它根本不可用）
 *   限制（`restrictToTags` / `actionLock`）— **负向、排除**、**全局**
 *     "除了白名单里的，其它都不行"
 *
 * 派生**不需要新引擎机制**：`checkGate` 已经会执行技能的 `requires`
 * （失败返回 `condition`），所以派生技只要写
 * `requires: [{ kind: 'hasBuff', buffId: 'combo-window' }]` 就行。
 *
 * ==================================================================
 * ⚠️ 为什么把"源技能"记在 flags 里
 * ==================================================================
 *
 * 需求："用掉就消失了，键盘派生技能显示在**原技能的上方**"
 *       "同一时间同一个派生出来的技能只能出现一个（如果另一个技能
 *        也能派生『击』，同时也只能派生一个击，**后派生的顶掉先派生的**）"
 *
 * UI 必须知道"这次派生是从谁那儿来的"才能画在它上方。而"顶掉"意味着
 * **源是动态的** —— 静态的 `SkillDef.derivedFrom` 表达不了"这一轮是
 * 「截」派的、下一轮可能是别的"。记在 flags 上则天然满足顶掉：
 * 同一个 buff id 刷新时 flags 一起被覆盖。
 *
 * ⚠️ 现在这个 `comboWindowSource: 'jie'` 是**P3 的占位**（见文件头）：
 * 今天没有代码挂这个 buff，所以这个值不会被任何 UI 读到。保留它是因为
 * 它记录了"窗口迟早要记源技能"这条已经定了的设计。
 */
export const COMBO_WINDOW: BuffDef = {
  id: 'combo-window',
  nameKey: 'buff.comboWindow.name',
  icon: 'char_combo',
  polarity: 'buff',
  color: C.focus,
  /**
   * 窗口时长 0.8 秒 = 8 个逻辑步。
   *
   * 短到"必须马上用掉"、长到"按得过来"：比一个「击」的施放稍长，
   * 但短于任何一次 Boss 前摇 —— 所以它是"看到打断成功立刻接一发"
   * 的节奏，而不是可以一直捏着的资源。
   */
  duration: logicMs(8),
  maxStacks: 1,
  stacking: { mode: 'refresh' },
  /** UI 靠它把派生技画在源技能上方。见上面的说明。 */
  flags: { comboWindowSource: 'jie' },
};

/**
 * **一局肉鸽的炁机**给出来的派生窗口：与 `COMBO_WINDOW` 只差
 * `flags.comboWindowSource`。
 *
 * ==================================================================
 * 用户 2026-10-13 的定调：「**这个整体是一个炁机，不是 击 是炁机**」
 * ==================================================================
 *
 * 炁机 = **「源技能 → 派生技」这条关系本身**。所以：
 *   - 它是「截 派生 击」/「卸 派生 击」/「闪 派生 击」，不是"一个叫击的道具"
 *   - 源技能决定了窗口开在哪 —— 而"画在谁上方"读的正是
 *     `flags.comboWindowSource`（`viewAdapter` / `deriveSlots` 都在读它）
 *   - 同一个 `combo-window` buff id 反复刷新是**有意的**：同一个时间点
 *     只可能有一个窗口开着，而"后派生的顶掉先派生的"正是 `refresh` 语义
 *     （AGENTS.md §3b 的"唯一真相"同一条思路：窗口只有一份，源是它的字段）
 *
 * ⚠️ 于是**不需要**给「卸派生击」「闪派生击」各造一个派生技 ——
 * 派生技是同一个「击」（`STRIKE`），变的只是**它从谁那儿派出来**。
 * 这与 §5.2 的设计一致：窗口是那个关系，技能只是它的出口。
 */
export function comboWindowFor(sourceSkillId: SkillId): BuffDef {
  return {
    ...COMBO_WINDOW,
    flags: { comboWindowSource: sourceSkillId },
  };
}

/**
 * 「截」：**瞬发强打断** —— 成功则冷却归零，失败进入完整冷却。
 *
 * 需求（用户澄清）："我不是说加一个『截』吗 和 破是不一样的，截 才派生
 * 『击』"。
 *
 * ==================================================================
 * ⚠️ 与「破」的分工（两者**并存**，不是同一个技能）
 * ==================================================================
 *
 * | | 「破」 | 「截」 |
 * |---|---|---|
 * | 定位 | **稳定**的基础打断 | **高风险高回报**的强打断 |
 * | 冷却 | 固定 5 秒 | 10 秒，**成功则退还** |
 * | 派生 | 无 | ~~派生「击」~~ → **P3 由炁机接回** |
 * | 代价 | 10 炁 | 10 炁 |
 * | 归属 | 黛玄（还没做） | **凯丽** |
 *
 * 设计意图：`破` 是"随时能用的打断"，`截` 是"赌一把"—— 打空了要等
 * 10 秒。对玩家是"要不要为一次打断冒险"的选择。
 *
 * ⚠️ **2026-10-12：派生的那一半被用户暂时拿掉了**（原话见
 * `COMBO_WINDOW` 上面的文件头）。所以现在成功与失败的差别**只有
 * 冷却退不退**：
 *   - 成功 → `cooldown: -10s`（等于不进 CD）
 *   - 失败 → 那 10 秒冷却自然留着
 * 内容校验器那条"退还量必须与冷却相等"的断言仍然有效（值没变）。
 *
 * ⚠️ 默认**不绑键**（需求："不绑"）—— 玩家要在设置里自己绑。
 * 所以它默认不出现在技能栏与触屏按钮上，但**不是不能绑**。
 */
export const JIE: SkillDef = {
  id: 'jie',
  kind: 'activeSkill',
  nameKey: 'skill.jie.name',
  descKey: 'skill.jie.desc',
  icon: 'char_break',
  abilities: [],
  castTime: 0,
  /**
   * 冷却 10 秒 —— 与 `onSuccess` 里退还的量**必须完全相等**。
   *
   * ⚠️ 不相等会静默坏掉：退多了被"减到 `tick` 以下"钳住（看起来对，
   * 但掩盖了配置错误）；退少了成功之后还剩一截 CD（玩家会以为
   * "怎么还在转"）。所以 `content/validate.ts` 有一条断言强制相等。
   */
  cooldown: logicMs(100),
  cost: [{ resource: 'energy', value: S(10) }],
  targeting: { mode: 'primaryEnemy' },
  hits: [
    {
      at: 0,
      effects: [
        {
          kind: 'interrupt',
          target: { mode: 'primaryEnemy' },
          force: true,
          /**
           * ============================================================
           * **只有真打断到了才结算这一条**（需求："如果成功，不进入 cd"）
           * ============================================================
           *
           * `cooldown` 退还 —— 施放时已经扣了那 10 秒，这里减掉同样的量。
           * 不填 `skillId` = 调"当前这个技能自己"。
           *
           * ⚠️ **这里曾经还有第二条 `grantBuff: COMBO_WINDOW`**（"成功就
           * 派生「击」"）。2026-10-12 用户要求"**把现在的截的派生去掉**"
           * —— 见文件头与 `docs/specs/2026-10-12-player-kits.md`。
           * 不要"顺手加回来"：P3 会从**炁机**那条路接，而不是从「截」。
           *
           * ⚠️ 失败（Boss 没在读条 / 带霸体）时这条也不结算，那 10 秒
           * 冷却就自然留着 —— 正是需求要的"失败则 cd 10 秒"。
           */
          onSuccess: [{ kind: 'cooldown', cooldownMs: -logicMs(100) }],
        },
      ],
    },
  ],
  tags: [],
  /**
   * ⚠️ 原先这里还有 `hintTags: ['interrupt']`，已删 —— 提示现在从
   * `hits[].effects` 里的 `interrupt` 效果推导（见 `app/skillHints.ts`）。
   */
  interruptible: false,
};

/**
 * 「击」：**派生技**，无消耗，伤害是「斩」的一半。
 *
 * 需求："新增『击』这个技能，伤害比攻少一半，但是没有消耗。"
 *
 * ==================================================================
 * ⚠️ 它今天**永远用不出来**（预期，不是 bug）
 * ==================================================================
 *
 * `requires` 认的 `combo-window` **没有任何产出者**（「截」的那一条被
 * 用户要求删掉了，见文件头）。所以：
 *   - 它在技能栏里不出现（`deriveSlots` 只在窗口开着时插槽位）
 *   - 即使有人硬发一个 `useSkill: 'strike'`，`checkGate` 也会以
 *     `condition` 拒掉
 *
 * **保留**它的理由与判据在文件头（AGENTS.md §2：未实现 → 保留 + 标注 +
 * 拒绝静默误用）。P3 的炁机会把窗口开回来，那时这个技能立刻就能用。
 *
 * ⚠️ 它**不在任何键位里**、也不由玩家直接按出：
 *   - 键盘：`Ctrl/Cmd + 原技能键`（见 `input/keyboard.ts`）
 *   - 触屏：画在原按钮上的角标环
 * 平时它**不可用**（`requires` 不满足），所以不占技能栏。
 */
export const STRIKE: SkillDef = {
  id: 'strike',
  kind: 'activeSkill',
  nameKey: 'skill.strike.name',
  icon: 'char_attack',
  descKey: 'skill.strike.desc',
  abilities: [],
  /** 瞬发 —— 它接在打断之后，不该再让玩家等读条。 */
  castTime: 0,
  cooldown: 0,
  /** 需求："没有消耗"。 */
  cost: [],
  targeting: { mode: 'primaryEnemy' },
  /**
   * ⚠️ **这就是"派生"的开关**：没有 `combo-window` buff 时，这一条
   * 让 `checkGate` 直接以 `condition` 拒掉 —— 也就是"这个技能根本
   * 不可用"，而不是"可用但被排除"（那是「限制」的语义）。
   */
  requires: [{ kind: 'hasBuff', who: 'self', buffId: 'combo-window' }],
  hits: [
    {
      at: 0,
      effects: [
        {
          kind: 'damage',
          /** 「斩」是 `S(10)`，所以这里 `S(5)` —— "伤害比攻少一半"。 */
          damage: { base: S(5), canCrit: false, countsAsHit: true },
        },
        /**
         * **用掉就消失**（需求）。
         *
         * 移除派生窗口本身 —— 于是"一次打断只换来一次「击」"。
         * 不这么做的话窗口期内能反复放，派生技会完全取代基础技。
         */
        { kind: 'removeBuff', target: { mode: 'self' }, buffId: 'combo-window' },
        /**
         * ⚠️ **「击」也是攻击**，所以它同样要消耗「避实击虚」的蓄势。
         *
         * 不写这一条的话，蓄势会**穿过**一次攻击活下来（下一击再翻倍）
         * —— 与用户说的"下一次攻击"不符。契约在 `kits/dodgeCharge.ts`
         * 的文件头（含"为什么不能靠 `Ability: 'consume'`"）。
         *
         * ⚠️ 与上面那条一样，**没有那条炁机时是空操作**。
         */
        { kind: 'removeBuff', target: { mode: 'self' }, buffId: DODGE_CHARGE.id },
      ],
    },
  ],
  tags: ['melee'],
  interruptible: false,
};
