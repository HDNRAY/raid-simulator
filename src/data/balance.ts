/**
 * 战斗数值常量 —— **引擎与内容共用的刻度定义**。
 *
 * ------------------------------------------------------------------
 * 为什么这些常量住在 data/ 而不是 core/
 * ------------------------------------------------------------------
 *
 * 它们**不是引擎机制**，而是本作的数值选择：
 * "每点伤害换多少缠"可以是 1、也可以是 0.5，换个游戏就变了。
 * 引擎只负责执行 `缠 += 伤害 × 系数` 这条规则，系数由内容给。
 *
 * 放在 core/ 会让引擎依赖具体数值；放在 content.ts 会导致
 * 引擎反向依赖内容文件。所以单独一个顶层常量文件，两边都能读。
 *
 * ------------------------------------------------------------------
 * 两种刻度必须分清（这是踩过坑的地方）
 * ------------------------------------------------------------------
 *
 *   **展示刻度** ——  玩家看到的数字：100 血、10 伤害、1 点资源
 *   **内部刻度** ——  引擎存储的数字：展示值 × `DISPLAY_SCALE`
 *
 * **任何跨刻度的系数都必须显式换算。** 反例：把展示刻度的
 * "1 缠/伤害"直接乘内部刻度的伤害，资源就会攒得快 10 倍，
 * 玩家一路「轰」秒杀 Boss（实测 7 秒通关一场本该 2 分钟的战斗）。
 *
 * ------------------------------------------------------------------
 * 标识符与中文名的对应（容易搞混，写在这里）
 * ------------------------------------------------------------------
 *
 *   `energy` → **炁**  短循环资源，每 0.1 秒自动回复
 *   `douqi`  → **缠**  积攒型资源，按伤害换算
 *
 * `douqi` 不是"斗炁"的缩写 —— 这两个中文名在 2026-10-09 对调过一次，
 * 标识符出于历史原因保留了。**改中文名只动 `i18n/locales/`**。
 */

/**
 * 刻度倍率。**现在恒为 1**（内容刻度 = 展示刻度）。
 *
 * 保留这个常量是因为 UI 层仍然用 `internal / DISPLAY_SCALE` 做显示换算 ——
 * 将来若需要把内部刻度放大（例如加入需要小数精度的机制），
 * 改这一个数字就能让两侧同时跟上。
 */
export const DISPLAY_SCALE = 1;

/**
 * 每 0.1 秒恢复的**炁**（`energy`，展示刻度）。→ **10 点/秒**。
 *
 * ==================================================================
 * 这个数是"输出上限"的真正来源
 * ==================================================================
 *
 * 玩家的**总输出被它卡死**：T 秒最多打出 `10 × T` 点（全部炁给「斩」），
 * 而每次闪避都从同一个池子里抽走一份。所以：
 *
 * | 技能 | 炁耗 | 折算成"秒" |
 * |---|---|---|
 * | 「斩」 | **15** | 1.5 秒的炁 |
 * | 「避」 | **15** | 1.5 秒的炁 |
 * | 「破」/「截」 | 10 | 1 秒 |
 *
 * ⚠️ 2026-10 的一次改动：`斩` 与 `避` 都变成了 **15**（原先 10 / 30）。
 * 两边的后果都在那一对数字里 ——
 *   - 「斩」变贵 → 炁养得起的持续输出从 **10/s 降到 6.7/s**（打得慢了）
 *   - 「避」变便宜 → 一次闪避从"少打 3 次斩"降到"少打 1 次"（躲得起了）
 *
 * 所以"该躲时躲不躲得起"完全由它决定，**调它请先读 `bossHp.ts` 的实测表**。
 */
export const ENERGY_PER_LOGIC_TICK = 1;

/**
 * 林晚风「卸」的**阈值 N**（展示刻度）。
 *
 * ⚠️ 显示名是「卸」，而常量名/技能 id 是 `GUARD_THRESHOLD` / `guard`
 * —— 名字不准确是**已知且有意保留**的（`skillId` 是持久化键），
 * 理由写在 `kits/linwanfeng.ts` 的 `GUARD` 与 player-kits §3.0。
 *
 * ==================================================================
 * 规则（用户定的口径）
 * ==================================================================
 *
 * ```
 * 这一击的伤害 ≤ N  →  完全抵消（0 伤害，且【连它带的效果一起免】，如眩晕）
 * 这一击的伤害 >  N  →  伤害 − N（效果【照吃】）
 * ```
 *
 * - **多段攻击按【每一段】各减一次**（用户已确认）。
 * - 判据是"**这一击结算出来的伤害值**"（含增伤 / 易伤 / 暴击，
 *   但**不含**防御侧的减免）—— 见 `core/combat/index.ts` 的
 *   `computeDamage`：先算出 `preBlock`，再和 N 比。
 *
 * ==================================================================
 * ⚠️ 为什么它住在这里（而不是写在内容里）
 * ==================================================================
 *
 * 用户的调参口径："**如果太强，阈值可以改成 10**"。
 * 也就是说这个数**会被反复调**，所以它必须是一个**具名常量**：
 * 内容（`data/kits/linwanfeng.ts`）import 它，而不是散落一个字面量 15。
 *
 * 依赖方向与 `ENERGY_PER_LOGIC_TICK` 同一条：`data/` 下的常量文件，
 * `core/` 与内容**都能读**，而它自己不读任何人（不成环）。
 */
export const GUARD_THRESHOLD = 15;

/**
 * 林晚风「卸」按住期间**每个逻辑步**扣的炁（`SkillDef.holdDrain.perLogicTick`）。
 *
 * ==================================================================
 * ⚠️ 单位口径：设置页写的是"3 炁/秒"，引擎扣的是"3 炁/逻辑步"
 * ==================================================================
 *
 * 一个逻辑步 = 0.1 秒（`TICKS_PER_LOGIC_TICK`），而炁自然回复
 * `ENERGY_PER_LOGIC_TICK = 1`（= 10/秒）也是按同一刻度算的 —— 所以
 * 「卸」的真实支出是 **30 炁/秒**（净 20/秒），不是设置页上那个 "3 炁/秒"。
 *
 * 那个显示错误住在 `app/keyRows.ts`（它把 `perLogicTick` 直接当成
 * `/秒` 插进 `settings.detailCostPerSecond`），**不是这里**。
 * 本常量只负责一件事：让"改按住代价"只需改一处。
 *
 * ==================================================================
 * 用户的调参口径
 * ==================================================================
 *
 * "按住消耗 3 炁/秒（太强 → 5 炁/秒）" —— 与 `GUARD_THRESHOLD` 同一条
 * 口径，写在 `docs/specs/2026-10-12-player-kits.md` 的「调参杠杆」小节。
 * **当前值 3 不是待办**：只有实测"卸力太强"时才动它。
 *
 * 内容（`data/kits/linwanfeng.ts` 的 `GUARD`）import 它，不许把 3 写死回去。
 */
export const GUARD_HOLD_DRAIN_PER_LOGIC_TICK = 3;

/**
 * 每点伤害换多少**缠**（`douqi`，展示刻度）。
 *
 * 1 = "造成 1 点伤害得 1 点缠"，受到伤害同理。
 * 于是打满 100 伤害或挨满 100 伤害各攒满一次缠（上限也是 100）。
 * 「轰」「凝」这类高威力招式吃缠。
 */
export const DOUQI_PER_DAMAGE = 1;

/**
 * 引擎用的换算系数（**内部刻度**）。
 *
 * 伤害与缠现在是同一刻度，所以就是 `DOUQI_PER_DAMAGE`。
 * 保留这个别名是为了让调用点的语义清楚（"引擎内部用的那个"）。
 */
export const DOUQI_PER_INTERNAL_DAMAGE = DOUQI_PER_DAMAGE;
