/**
 * 固定步长相关的常量。
 *
 * 单独成文件是因为 SimClock（worker 内部推进用）和 FixedLoop（主线程渲染驱动用）
 * 都要用它们。把常量放在两者之一都会造成循环依赖。
 */

/** 固定步长：60Hz。任何地方都不许改这个值（改了会让所有黄金测试失效）。 */
export const DT = 1000 / 60;

/** 单帧最多补多少毫秒。防止标签页休眠后回来一次性补几千帧（死亡螺旋）。 */
export const MAX_CATCHUP_MS = DT * 5;

/**
 * 浮点容差：1 纳秒。
 *
 * 累加器是 `n * DT` 的浮点和，而 DT = 1000/60 是无限循环小数，
 * 所以几乎永远不精确等于 `n * DT`。例如 60 * DT = 1000.0000000000001，
 * 而逐帧累加 60 次得 999.9999999999999 —— 差 1.4e-13，
 * 于是"喂 60 帧却只推进 59 步"。
 *
 * 1e-9 ms 是一帧的百万分之一，不会造成真实步进偏差，但足以吸收这层噪声。
 */
export const TIME_EPSILON = 1e-9;
