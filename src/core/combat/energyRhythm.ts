/**
 * **回炁的"整数节奏"** —— 「恶魔低语」的"回炁变慢 80%"（2026-10-16）。
 *
 * ==================================================================
 * 为什么不是"每步回复 × 0.8"
 * ==================================================================
 *
 * 两条路都会被取整吃掉，而且**不报错**：
 *
 * | 做法 | 结果 |
 * |---|---|
 * | 每步 `+0.8` | `changeResource` 是 `Math.round(before + delta)`，资源是**整数** ⇒ 每步照样 `+1` ⇒ **一点都不慢** ✗ |
 * | 走 `energyRegen` 属性 | 它按 `Math.floor(每秒 / 10)` 落到每步 ⇒ `8/秒 → 0` ⇒ **完全不回** ✗（比设计狠 5 倍） |
 *
 * 所以用**整数节奏**表达比例：`scale = 0.8` ⇒ **每 5 个逻辑步只回 4 点**
 * （8/秒 ✓ 精确）。它**无状态**（只看第几个逻辑步）、不动确定性、
 * 不动回放格式 —— 与"时间只有两个刻度"这条纪律同一路。
 *
 * | scale | 周期（每几步跳 1 步） | 实际 |
 * |---|---|---|
 * | 0.8 | 5 | 8/秒 ✓ |
 * | 0.9 | 10 | 9/秒 ✓ |
 * | 0.75 | 4 | 7.5/秒 ✓ |
 * | 0.5 | 2 | 5/秒 ✓ |
 * | 0.7 | 3 | 6.67/秒 ≈（**近似**，周期必须是整数，见下） |
 *
 * ⚠️ 周期必须是整数 ⇒ 不是每个比例都精确（0.7 → 6.67 而不是 7）。
 * 当前内容只用 0.8，精确。要更精确就得加小数欠账（一个新状态字段 +
 * 回放格式的账）—— 不值得，判据写在这里。
 */

/** 一个周期里跳过的那一步（周期内的第几个）。 */
const SKIP_AT = 1;

/**
 * 这一步要不要**跳过回炁**。
 *
 * @param step 第几个**逻辑步**（`tick / TICKS_PER_LOGIC_TICK`，整数）
 * @param scale 倍率（基准 1；< 1 才生效）
 */
export function skipEnergyRegenStep(args: {
  readonly step: number;
  readonly scale: number;
}): boolean {
  if (!(args.scale < 1)) return false;
  if (!(args.scale > 0)) return true;
  const period = Math.max(2, Math.round(1 / (1 - args.scale)));
  return ((args.step % period) + period) % period === SKIP_AT - 1;
}
