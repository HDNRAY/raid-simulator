/**
 * **开发模式的常量**（2026-10-20，用户："我们现在有 config.ts 来写一个
 * 开发模式的常量吗？没有就加一个，开发模式，显示所有炁机"）。
 *
 * ==================================================================
 * 为什么是**常量**而不是环境变量
 * ==================================================================
 *
 * 这个仓库只有一条"构建期开关"的先例：`import.meta.env.DEV`（见
 * `app/viewHelpers.ts` 的短标签告警）—— 那是"打包器给的"，用来
 * **只在开发构建里**打日志。而这里的用途完全不同：**真正玩的时候临时看一眼
 * 全部内容**（图鉴里未解锁的炁机也要显示名字与说明）。
 *
 * 所以它是一条**源码里的常量**：改一行就能开，不需要重启构建配置、
 * 也不会因为"忘了 `pnpm dev`"而在 `vite preview` / 打包后的页面上失效。
 *
 * ==================================================================
 * 怎么开
 * ==================================================================
 *
 * ```
 * ① 改这里：DEV_MODE = true          ← 最直接，改完刷新页面
 * ② 跑的时候加参数：?dev=1            ← 不改代码也能验（截图脚本用这个）
 * ③ 关掉：?dev=0 或删掉参数
 * ```
 *
 * ⚠️ **它只影响"看得到什么"，不影响任何战斗逻辑**：图鉴里把未解锁的炁机
 * 也显示出来（名字 + 说明），**不会**把它们加进肉鸽的候选池、也不会替玩家
 * 解锁 —— 那是 `RunState.unlocked` 与 `unlock.ts` 的事。
 */
export const DEV_MODE = false;
