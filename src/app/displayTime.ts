/**
 * **毫秒 → 秒的显示值**：一处实现，不丢精度。
 *
 * ==================================================================
 * 为什么单独一个文件（而不是在 `keyRows.ts` 里留一个局部函数）
 * ==================================================================
 *
 * 这个换算有**两个**调用点（设置页的结构化「冷却」与「施放」），而且
 * 内容里还有一串「秒」要显示（`app/descParams.ts` 的模板参数）。
 * 各写一遍就是"同一件事两份表达"—— 本仓库反复踩过的那个形态：
 * 修了一处、另一处继续显示旧值，而且不报错。
 *
 * ==================================================================
 * 它修的是什么（用户报告的原始症状）
 * ==================================================================
 *
 * 「闪」的冷却住在 `FLASH.cooldown = logicMs(6)` = **600 毫秒**，也就是
 * **0.6 秒**。而设置页显示的是 `Math.round(600 / 1000)` = **1** ✗ ——
 * 玩家看到的 1 秒比内容定义的 0.6 秒多了 67%。
 *
 * ⚠️ 修法**不是** `toFixed(1)`：那会把 `5` 显示成 `5.0`（尾零是噪声），
 * 而 0.6 恰恰要显示成 `0.6`。所以判据是"**值本身**"：
 *   0.6 → `0.6`    5 → `5`
 *
 * 做法：先把毫秒折成 0.1 秒刻度上的**整数**，再除以 10。
 *
 *   `Math.round(600 / 100) / 10` = `6 / 10` = **0.6** ✓
 *   `Math.round(5000 / 100) / 10` = `50 / 10` = **5** ✓
 *
 * ⚠️ 为什么先除 100 再除 10：那一步把 0.1 秒刻度上的值**变成整数**再舍入
 * （0.6 → 6、5 → 50），于是"四舍五入"发生在整数上，不会带上
 * `logicMs(2) / 1000 = 0.19999999999999998` 这类浮点尾数。最后那一次
 * 除以 10 是精确的（`6 / 10` 与 `50 / 10` 都给出可读的值）。
 *
 * ⚠️ 为什么是 **0.1 秒**粒度：本作的逻辑最小单位就是 0.1 秒
 * （`LOGIC_TICK_MS`）。内容里写的时间都声明在逻辑步上，所以
 * "折到 0.1 秒"不是丢精度，而是**本来就只有这个精度**（`logicMs(6)` = 0.6）。
 * 真有内容声明了 0.05 秒这种更细的值，它会被折到最近的 0.1 —— 那超出
 * 本作的逻辑精度，属于内容错误（`logicTicks()` 对非整数步直接抛错）。
 *
 * ⚠️ 它只给**静态内容数值**用（设置的冷却 / 施放、说明模板里的秒数）。
 * 战斗中的**剩余时间倒计时**另有口径（`Math.ceil` 向上取整，因为"还剩
 * 0.2 秒"显示成 0 会让玩家以为已经好了），不在本函数职责内。
 */

/**
 * 毫秒 → 秒（折到 0.1 秒刻度）的**数字**，交给 i18n 模板插值。
 *
 * 返回数字而不是字符串：`{seconds}` 这个占位符由 `t()` 按当前语言格式化，
 * 在这里拼字符串就等于把显示格式抄出 i18n 之外。
 */
export function displaySeconds(ms: number): number {
  if (!Number.isFinite(ms)) return 0;
  /**
   * ⚠️ **先取整到 0.1 秒刻度（`Math.round(ms / 100)`），再除以 10。**
   *
   * 直接写 `ms / 1000` 会带浮点尾数（`200 / 1000 = 0.2` 恰好，
   * 但 `logicMs(2.5) / 1000 = 0.25`、而更一般的值会给出
   * `0.19999999999999998` 那种）；而先乘后除（`Math.round(ms * 10) / 10`）
   * 得到的是**毫秒的十分之一** —— 600 会变成 600，不是 0.6。
   */
  return Math.round(ms / 100) / 10;
}
