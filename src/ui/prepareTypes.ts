/**
 * **备战屏（自由模式）的形状**：光标槽位 + 一个可选项。
 *
 * ==================================================================
 * 为什么单独一个文件（而不是塞进 `prepareLogic.ts`）
 * ==================================================================
 *
 * 这三个类型**同时被三个文件引用**，而其中一个（`prepareLayout.ts`）
 * 是"纯几何"——它不该为了一个类型去 import 整个状态机。放进这里之后：
 *
 * ```
 *   prepareTypes  ←─ prepareLayout（几何：焦点槽位决定画哪一行）
 *         ↑───────  prepareLogic （状态机）
 *         ↑───────  prepareDetail（详情区读"当前焦点/光标"）
 * ```
 *
 * 依赖是**单向**的（类型 → 无依赖），所以不会成环。
 *
 * ⚠️ 与 `ui/qijiSelectLogic.ts` 的 `QijiView` **刻意不同**：那一份带
 * 名字 / 描述 / 图标（选炁机屏要自己画卡片），而这一屏的卡片只画名字，
 * 图标/描述一律交给 `prepareDetail`。两者形状不一样是**有意的** ——
 * 硬合成一个接口会让"这一屏需要什么"这件事变模糊。
 */

/**
 * 焦点所在的槽位。
 *
 * ⚠️ 顺序（在 `prepareLogic.moveFocus` 里）是
 * **人物 → 炁机 → 对手 → 开始**：炁机紧贴人物，因为需求是
 * "**选了人之后**，可以激活任意个他的炁机"。
 */
export type PrepareFocus = 'player' | 'qiji' | 'boss' | 'start';

/** 可选项（只要 id —— 显示名由渲染层按 i18n 取）。 */
export interface PrepareOption {
  readonly id: string;
}
