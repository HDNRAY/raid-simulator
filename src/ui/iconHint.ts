/**
 * **图标按钮的键位提示：几何**（纯函数，不碰 Pixi）。
 *
 * ==================================================================
 * 摆法：**角标**（提示压在图标**左上角**上）—— 昨天那一版，用户指认的规格
 * ==================================================================
 *
 * ⚠️ 2026-10-13 用户原话："**是角标在左上角啊？** 你随便找个【昨天】的版本
 * 都是这样。今天我让你把返回改得跟设置一样之后，就都不对了，**没一次是对的**。"
 *
 * 他指的参照物是 **`e64eb2d`**（昨天最后一个"角标"提交，10-12 22:29）。
 * 那一版把提示画成一枚**压在图标左上角上**的小角标：
 *
 * ```ts
 * // src/ui/IconButton.ts @ e64eb2d —— 它是这么摆的
 * const corner = hintSide === 'corner';
 * this.hint = new Label(pixi, {
 *   size:  corner ? ICON_BUTTON_DEFAULTS.cornerSize   : FONT.small,  // 9  vs 13
 *   color: corner ? PALETTE.text                      : PALETTE.textDim,
 *   ...(corner ? { stroke: 0x000000, strokeWidth: 3 } : {}),         // 描边 3
 * });
 * // 落位：提示的【左上角】= 图标的【左上角】—— 没有偏移量
 * return { x: icon.x, y: icon.y, anchorX: 0, anchorY: 0 };
 * ```
 *
 * ⚠️ **`corner` 的两条几何特征就是"角标"本身**，两者缺一不可：
 *   - **更小的字号**（`cornerSize` 9 < `FONT.small` 13）：它是附注，不是同行元素
 *   - **黑描边 3px**：它**压**在图标浅色笔画上（齿轮尤其明显），没有描边会糊
 *     成一团（用户报过"esc 的描边没有让它看起来足够清晰"，加粗到 3 才好）
 *
 * ⚠️ **`41ca468` 那次"恢复历史"挖错了版本**：它挖到了**首个提交**
 * （`d4e3fb7`）的"并排"（`⚙ F1` / `F1 ⚙`，提示与图标同一行、垂直居中），
 * 把角标整个拿掉了 —— 而用户要的从来不是并排。这次直接照 `e64eb2d` 抄。
 *
 * ==================================================================
 * ⚠️ 一条规则，**没有"看按钮在画布哪一半"的分支**
 * ==================================================================
 *
 * 老版由**每个按钮自己配** `hintSide`，而两个按钮配的都是 `'corner'`
 * （`ScreenChrome` 里齿轮与返回箭头各写了一次）—— 取值一致，所以是一套外观。
 *
 * 用户否掉的是另一件事：更早的 `hintCorner: 'auto'` 会**按按钮在画布哪一半
 * 自动翻边**，于是"左上角的返回"和"右上角的齿轮"看起来是两套算法
 * （原话："**不用看在哪一半，全局统一风格**"）。
 *
 * 现在没有"哪一侧"这个输入了：**提示的左缘比图标左缘再往左一点（`shift`）、
 * 上缘比图标上缘再往上一点（`rise`）** —— 两个按钮、战斗齿轮、任何缩放系数
 * 都走同一条公式（两个偏移见 `HINT_SHIFT` / `HINT_RISE`）。
 *
 * ==================================================================
 * ⚠️ 提示整块**跟着图标缩放**（用户要求，与摆法是两件事）
 * ==================================================================
 *
 * 规格是：字号 + 落位**跟图标一起缩**，而且**一条公式**（只有图标边长一个输入）：
 *
 *     字号 = max(MIN_HINT_FONT, round(hintFont × size / BASE_ICON))
 *
 * ⚠️ **下限由规则给出**（`MIN_HINT_FONT = 8`），不是"算完再夹一下"：
 * 0.5 倍时按比例是 `round(13 × 0.5) = 7`，而 7px 的拉丁字母 + 数字已经糊成
 * 一团，8 是还能一眼认出来的下限。它只在缩放 < 0.615 时生效。
 *
 * ⚠️ 上限不需要：提示永远只有图标的一半高（比例固定），不会抢过图标。
 *
 * ⚠️ 这一条是**叠加在角标上的**：`hintFont` 说的仍是"20px 图标时提示多大"
 * （角标的 9px），缩放与下限照旧。
 *
 * ==================================================================
 * ⚠️ 为什么这些算术单独一个文件（AGENTS.md §3：关注分离）
 * ==================================================================
 *
 * 原来它们住在 `ui/IconButton.ts` 里，而那个文件本身是"一个组件"
 * （构造 Pixi 节点、命中测试、悬停 / 焦点外观）—— **"提示画在哪、多大"
 * 是另一件事**，它有这些消费者：
 *
 *   1. `IconButton` 自己（画那行提示、算包围盒）
 *   2. `ScreenChrome`（战斗齿轮的落位要按"面板右缘 + 提示/图标"反推）
 *   3. 单测（`tests/unit/iconButtonHint.test.ts` / `iconButton.test.ts`）
 *
 * 而且 `IconButton.ts` 当时已经 682 行（贴着 700 的上限）。**不许靠压注释
 * 腾地方**，所以按职责切开：几何 + 它的常量搬到这里，组件文件只留
 * "造 / 画 / 命中"。
 */

/** 基准图标边长 —— 比例的分母（`hintFont` 说的是这一档）。 */
export const BASE_ICON_SIZE = 20;

/**
 * 基准字号：20px 图标时提示用 **9px**（角标那一档）。
 *
 * ⚠️ 这就是 `e64eb2d` 的 `ICON_BUTTON_DEFAULTS.cornerSize`（9），**不是**
 * `FONT.small`（13）。13 是并排摆法的值 —— 那时提示与图标同一行、是同级元素，
 * 所以可以一样大；角标压在图标角上，必须明显小一圈（原话："esc 应该比较小，
 * 然后再设置按钮的左上角"）。
 *
 * ⚠️ 它**比 `FONT.tiny`（11）还小一号**，所以这里不能转发 `FONT` 里任何一档：
 * 角标不是"某一号正文"，它是图标上的附注。字号表里也没有 9 这一档。
 */
export const BASE_HINT_FONT = 9;

/**
 * 提示字号的**下限**（px）—— 缩放规则自己给出的那一条。
 *
 * 0.5 倍时按比例算出来是 `round(9 × 0.5) = 5`（角标比并排更小，所以下限
 * 更早生效），而 5~7px 的拉丁字母 + 数字已经认不出字形，8 是下限。
 *
 * ⚠️ 它**不是**"算完再夹一下"：规则本身写成
 * `max(MIN_HINT_FONT, round(hintFont × size / 20))`，所以"任何缩放系数下
 * 都看得清"是**规则的一部分**，不是第二套兜底。
 */
export const MIN_HINT_FONT = 8;

/**
 * 角标在**基准图标（20px）**上比图标上缘再往上抬多少（逻辑像素）。
 *
 * ==================================================================
 * ⚠️ 这是**用户 2026-10-13 给的偏移**，不是我自己发明的
 * ==================================================================
 *
 * 原话："**f1 还要再往上挪几个 px**"。
 *
 * 老版（`e64eb2d`）是"**提示左上角 = 图标左上角**"（`rise = 0`）——
 * 现在这条把它再往上压 `HINT_RISE`，也就是：
 *
 * ```ts
 * 提示左上角 = ( icon.x , icon.y − rise )
 * ```
 *
 * ⚠️ 只动 `y`：`x` 仍然是图标的左缘（用户只说了"往上"）。
 *
 * ==================================================================
 * ⚠️ 它**跟着图标缩放**（与字号同一条理由）
 * ==================================================================
 *
 * 选**按比例**而不是"固定 4px"，理由是"抬多少"属于**字形相对图标的姿态**，
 * 与字号是同一类量：放大 2 倍之后字高 18px 而抬升仍只有 4px，那 4px 在
 * 视觉上就"粘"在图标上了（相对间距缩水一半）。
 *
 * 所以这里走**与字号完全相同的那条公式**（同一个分母、同一个 `Math.round`）：
 *
 * ```ts
 * rise = round(HINT_RISE × size / BASE_ICON_SIZE)      // 20px 图标 → 4；40px → 8
 * ```
 *
 * ⚠️ 与字号不同的唯一一点：它**没有下限**（字号有 `MIN_HINT_FONT`）。抬升
 * 不是"读不读得清"的问题，缩小到 0 也仍然正确（只是不做偏移）。
 *
 * ⚠️ **上限由锚点那条规则保证**（不是算完再夹）：角标最多往上抬到
 * `图标上缘 − rise`，而所有调用点的图标上缘都 ≥ 安全区边距（`8×scale`）；
 * 于是 `rise ≤ 8×scale` 时它就**不会出画布**。基准 4 ≤ 8，按比例缩放后
 * 两边同时缩，所以 `HINT_RISE ≤ 8` 对任何系数都安全 —— 这个上限的推导
 * 写在 `iconHintPlacement` 里（那里也是唯一的落点）。
 */
export const HINT_RISE = 4;

/**
 * 抬升量（按图标边长推）—— 与字号同一条公式的"比例 + 取整"。
 *
 * 单独一个函数的理由：落位（`iconHintPlacement`）与单测都要读它，
 * 各写一遍 `Math.round(HINT_RISE * size / BASE_ICON_SIZE)` 必然漂。
 */
export function iconHintRise(size: number): number {
  return Math.round(HINT_RISE * (size / BASE_ICON_SIZE));
}

/**
 * 角标在**基准图标（20px）**上比图标左缘再往左挪多少（逻辑像素）。
 *
 * ==================================================================
 * ⚠️ 这也是**用户 2026-10-13 给的偏移**，与 `HINT_RISE` 成对
 * ==================================================================
 *
 * 原话（先）："**f1 还要再往上挪几个 px**" → `HINT_RISE`；
 * 原话（后）："**等会 往左再挪几个 px**" → 这一条。
 *
 * 于是落位现在是：
 *
 * ```ts
 * 提示左上角 = ( icon.x − shift , icon.y − rise )
 * ```
 *
 * ⚠️ **只动 `x` 与已有的 `y`** —— 字号 / 颜色 / 描边 / 锚点都没动。
 *
 * ==================================================================
 * ⚠️ 它与 `HINT_RISE` **用完全相同的处理**（刻意对称，不是巧合）
 * ==================================================================
 *
 * 两个量是同一类东西（"字形相对图标的姿态"），所以：
 *
 *   1. **跟 UI 缩放** —— 同一条公式、同一个分母、同一个 `Math.round`
 *      （固定值会让放大 2 倍后那 4px 显得"粘"在图标上）
 *   2. **没有下限**（字号才有 `MIN_HINT_FONT`）
 *   3. 都只在 `iconHintPlacement` 这一处被读（**不新开第二处**）
 *
 * ⚠️ **上限同样是 8**，理由与 `HINT_RISE` 完全对称：最靠左的调用点
 * （返回箭头）图标左缘 = 安全区 `round(8 × scale)`，而 `shift` 也按
 * `scale` 缩 —— 所以 `shift ≤ 8 × scale` 时它**不会顶出画布左缘**。
 * 基准 4 ≤ 8，对任何系数都安全。⚠️ 最紧的是**返回箭头**：scale 1 时
 * `8 − 4 = 4`（左边距剩 4px）、scale 2.0 时 `16 − 8 = 8`（仍在画布内）。
 * ⚠️ 所以**基准值最大能取 8**。
 *
 * ⚠️ 这段**不是**"越界再夹一下"：没有任何夹取，规则本身保证了上述不等式。
 * 真要取更大的值，先改的是**锚点的安全区**（按钮要不要往中间摆），
 * 不是在这里加兜底。
 */
export const HINT_SHIFT = 4;

/**
 * 左移量（按图标边长推）—— 与 `iconHintRise` 同形的"比例 + 取整"。
 *
 * 单独一个函数的理由与 `iconHintRise` 完全相同：落位与单测都要读它，
 * 各写一遍 `Math.round(HINT_SHIFT * size / BASE_ICON_SIZE)` 必然漂。
 */
export function iconHintShift(size: number): number {
  return Math.round(HINT_SHIFT * (size / BASE_ICON_SIZE));
}

/**
 * 提示的**字号**（按图标边长推）。
 *
 * 非整数 `size` 也接受（`Math.round` 收敛），但调用方给的都是整数
 * （`chromeBoxAt` / `computeContentBox` 都取整过）。
 */
export function iconHintFontSize(size: number): number {
  const scaled = Math.round(BASE_HINT_FONT * (size / BASE_ICON_SIZE));
  return Math.max(MIN_HINT_FONT, scaled);
}

/**
 * 估算等宽字体下一段文字的宽度。
 *
 * 存在的理由：`Text` 的宽度要等纹理生成才有值，而命中矩形必须在
 * 布局期定下来。等宽字体的字宽是稳定的（约 0.6em），所以估算足够准；
 * 这里取 0.62 并向上取整，**宁宽勿窄** —— 估窄了会出现
 * "看起来在按钮里、点不到"，以及"看着没出画布、实际被裁"。
 */
export function estimateMonoWidth(text: string, fontSize: number): number {
  return Math.ceil(text.length * fontSize * 0.62) + 4;
}

/**
 * 提示文字的**包围盒尺寸**（估算；与落位、截图脚本的 `hintBounds` 用同一套）。
 *
 * ⚠️ 角标摆法下它**不占**按钮的布局宽度（那是并排的特征）：提示压在图标的
 * 坐标范围里，所以可点区域只由图标 + `hitSlop` 决定。这个盒子只用来
 * 报"提示真的画在哪儿"。
 */
export function iconHintBoxSize(
  shortcut: string,
  size: number,
): { readonly w: number; readonly h: number } {
  const fontSize = iconHintFontSize(size);
  return { w: estimateMonoWidth(shortcut, fontSize), h: fontSize };
}

/** 落位要看的几何：图标矩形、画布多大。 */
export interface IconHintInput {
  readonly icon: { readonly x: number; readonly y: number; readonly w: number; readonly h: number };
  readonly canvasW: number;
  readonly canvasH: number;
}

/** 提示左上角要落到哪儿 —— 以及它的锚点（永远是左上角）。 */
export interface IconHintPlacement {
  readonly x: number;
  readonly y: number;
  readonly anchorX: number;
  readonly anchorY: number;
}

/**
 * 提示的**落位** —— 纯函数（可在 node 里测，不碰 Pixi）。
 *
 * ==================================================================
 * 规则（一条，两个按钮、任何缩放共用）
 * ==================================================================
 *
 * 设图标矩形为 `(ix, iy, iw, ih)`、抬升 `rise = iconHintRise(iw)`、
 * 左移 `shift = iconHintShift(iw)`：
 *
 * ```
 * 提示的【左上角】 = ( ix − shift , iy − rise )
 * ```
 *
 * 也就是**提示的左缘比图标左缘再往左一点、上缘比图标上缘再往上一点**
 * —— 提示因此是一枚**压在图标左上角上的角标**（横向压着、纵向比角略高），
 * 而不是"贴在旁边"或"压在中间"的东西。锚点是提示的左上角
 * （`anchorX/Y = 0`），提示**往右下方**长。
 *
 * ⚠️ 老版（`e64eb2d`）是 `(ix, iy)`（两个偏移都是 0）。用户 2026-10-13
 * 两句原话叠成现在这条：
 *   1. "**f1 还要再往上挪几个 px**" → `y` 减 `HINT_RISE`
 *   2. "**等会 往左再挪几个 px**" → `x` 减 `HINT_SHIFT`
 *
 * **只动了这两个量**（字号 / 颜色 / 描边 / 锚点都保持）。两个量的处理
 * **完全对称**（都跟缩放、都没有下限、都只在这里被读）。
 *
 * ==================================================================
 * ⚠️ 为什么它自己就保证不出画布（上限 `HINT_RISE ≤ 8`、`HINT_SHIFT ≤ 8`）
 * ==================================================================
 *
 * 角标的左缘 = `图标左缘 − shift`、上缘 = `图标上缘 − rise`。而调用点的
 * 边距都来自**安全区 8**：
 *
 * | 调用点 | 图标上缘 / 左缘 | 来源 |
 * |---|---|---|
 * | 全屏界面的齿轮 / 返回箭头 | 上、左都是 `round(8 × scale)` | `chromeBoxAt`（贴边） |
 * | 战斗齿轮 | 左 = 玩家面板右缘 + 间距；上 = 面板上缘（`≥ 444`） | `battleGearBoxAt` |
 *
 * 于是"不出画布"等价于 `rise ≤ 8 × scale` **且** `shift ≤ 8 × scale`，
 * 而两个量都按 `scale` 缩放（`round(N × size/20)`，`size = round(20 × scale)`），
 * 两边同时缩 —— **只要 `N ≤ 8`，任何系数下都成立**。
 *
 * ⚠️ 最紧的是**返回箭头**（它同时靠上、靠左）：
 *   - `rise`：scale 2.0 时 `16 − 8 = 8`（上缘）
 *   - `shift`：scale 1 时 `8 − 4 = 4`（左边距剩 4px）、scale 2.0 时 `16 − 8 = 8`
 *
 * 战斗齿轮两头都很松。⚠️ 所以可用空间是 `8 × scale`，**两个基准值最大
 * 都能取 8**（再大就要在某个系数下顶出画布）。
 *
 * ⚠️ 这段**不是**"越界再夹一下"：没有任何夹取，规则本身保证了上述不等式。
 * 真要取更大的值，先改的是**锚点的安全区**（要不要把按钮往中间摆），
 * 不是在这里加一段兜底。
 *
 * ==================================================================
 * ⚠️ `iy + 4` 那一版就是用户说的"**左中**"（2026-10-12 第二次修正）
 * ==================================================================
 *
 * 那一版把提示上缘放在 `iy + hintOverlap(4)`（**往下** 4px），理由是"角标
 * 要压住那一角"。但图标只有 **20~22px** 高，往下一个 9px 的提示落在
 * `iy + 4 .. iy + 13` —— **纵向几乎居中**，横向又贴着左缘，看起来正是
 * 用户报的"**左中**"✗（原话："F1 位置不对，现在是左中"）。
 *
 * ⚠️ 现在这一条是**往上** 4px（`iy − rise`）**往左** 4px（`ix − shift`），
 * 方向与它相反 —— 不要看到"4px"就当同一件事（那一条是"往下压进图标中间"，
 * 这一条是"往左上抬出角"）。
 *
 * ⚠️ 旧版（更早）把锚点放在提示的**右下角**、且右缘对齐到 `ix + 4` ——
 * 那让提示以"图标左缘"为中心横跨，看起来也**在正中间**。两版都已被这条
 * 规则取代。
 *
 * ⚠️ **不做越界避让**（没有夹取、没有第二套逻辑）—— 用户 2026-10-12 明确
 * 否掉了（"别再加第二套避让逻辑"）。所以这里**故意不写兜底**：真有调用方
 * 把图标放到会溢出的位置，那是**它自己**的 bug，应当在截图/测试里看见，
 * 而不是被一段夹取悄悄推回来。
 *
 * ⚠️ `canvasW` / `canvasH` / `hintW` / `hintH` 仍在入参里（调用方要说明
 * "这块提示是画在哪张画布上的、有多大"，纯函数测试也靠它们做对账），
 * 但**规则本身不使用它们** —— 用不上就不看，正是"一条规则"的含义。
 * （`hintW` / `hintH` 是 `e64eb2d` 的签名，保留它们是为了让调用点逐字对得上。）
 */
export function iconHintPlacement(
  input: IconHintInput,
  hintW: number,
  hintH: number,
): IconHintPlacement {
  const { icon } = input;
  void hintW;
  void hintH;
  return {
    x: icon.x - iconHintShift(icon.w),
    y: icon.y - iconHintRise(icon.w),
    anchorX: 0,
    anchorY: 0,
  };
}
