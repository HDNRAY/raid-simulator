/**
 * **去掉文案里的强调标记**（`**…**`）—— 全仓库唯一一份。
 *
 * ==================================================================
 * 为什么需要它
 * ==================================================================
 *
 * 内容表用 `**` 标重点（例：「碾压」的"读条全程**霸体**"），那是**给读源码
 * 的人**看的重音标记。而 Pixi 的一段 `Text` 做不了**行内**加粗 —— 所以
 * 画到屏上之前必须把星号去掉，否则面板上会原样显示 `**霸体**`
 * （本仓库在详情区与设置页各踩过一次，截图可见）。
 *
 * ⚠️ 2026-10-22 从 `prepareDetailPanel.ts` 抽出来：图鉴的卡片也要画炁机的
 * 说明（同一个 `descKey`），两份 `replaceAll` 就会漂（一处改了另一处忘）。
 */

/** 去掉 `**` 强调标记（不动别的字符 —— 说明里的数字与顿号都要留着）。 */
export function stripEmphasis(text: string): string {
  return text.replaceAll('**', '');
}
