/**
 * 设置弹窗的**共享几何常量**。
 *
 * ==================================================================
 * 为什么单独一个文件（而且必须是**叶子**）
 * ==================================================================
 *
 * `ui/settings/logic.ts`（交互解析）与 `ui/settings/keyGridLayout.ts`
 * （网格几何）**都要**这些常量。如果它们留在 `logic.ts`，就构成循环：
 *
 *   logic.ts        →（要网格几何）→ keyGridLayout.ts
 *   keyGridLayout.ts →（要 KEY_GRID）→ logic.ts
 *
 * ESM 下循环依赖**不报错**，但会让一侧在初始化未完成时读到 `undefined`
 * —— 实测报 `Cannot destructure property 'gapX' of 'KEY_GRID' as it is
 * undefined`（`KEY_GRID_CAPACITY` 是模块级立即求值的，它在 `logic.ts`
 * 的表还没建好时就去读了）。
 *
 * 所以把这些常量**下沉成叶子**：两边都向下依赖它，谁也不再依赖谁。
 *
 * ==================================================================
 * ⚠️ 竖排只分成四段，数字全是**显式常量**（2026-10-12 重排）
 * ==================================================================
 *
 *   ```
 *   面板顶  0     ┌ tab 行 ────────────── 40..70
 *                 │ 格阵（最多 2 行）      88..184
 *                 │ 详情区（换行 + 可滚）  194..416   ← 左下
 *                 │ 提示两行               430 / 450  ← 左下
 *   面板底 520    └ 按钮                   478..504
 *
 *   右下角：模拟键位预览  x 428..624, y 264..454（画布）
 *   ```
 *
 * ⚠️ 格阵是 **4 列 × 2 行 = 8 格**（桌面）：加列是为了让「劈」「卸」也能
 * 配键，而**高度一个字都没动**（`KEY_GRID_BOTTOM` 只跟行数有关）。
 *
 * ⚠️ 这一版**故意不写"一层套一层的推导式"**：实测踩过两次 ——
 * 模块级推导式一旦引用还没求值的兄弟常量，轻则
 * `Cannot access 'X' before initialization`（TDZ），重则**静默算错**
 * （容量从 3 行变 5 行、详情区高 26px）。显式数字 + `settings.test.ts`
 * 里的自洽性断言（详情区不重叠 / 格阵不越界 / 预览不压格子）更好查。
 *
 * ⚠️ 改任何一个数字，都要让 `pnpm run test:run` 里那几条几何断言过。
 */

