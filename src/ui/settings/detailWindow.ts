/**
 * 技能详情区的**窗口数学**（纯函数，可在 node 里测）。
 *
 * ==================================================================
 * 为什么单独一个文件
 * ==================================================================
 *
 * `SkillDetail.ts` 是 Pixi 组件，"滚动了没有"这件事在 jsdom 里**测不了**
 * （Pixi v8 构造得起来、但画不出东西，所以只能写"能构造、不报错"那种
 * 零信息冒烟测试）。而这一轮要修的东西恰恰是**一行的算术错**（见下），
 * 所以把那段算术拿出来 —— 它不认识 Pixi，可以真的断言。
 *
 * ==================================================================
 * ⚠️ 2026-10-12：`maxLines` 里的 `viewRows() - 2` 让滚动**永不可达**
 * ==================================================================
 *
 * 修之前的写法是：
 *
 *   ```
 *   maxLines = min(DESC_MAX_LINES, viewRows() - 2)
 *   ```
 *
 * 而内容总行数是 `1（名字） + 说明折行数 + 1（代价）`，于是
 *
 *   ```
 *   total ≤ 1 + (viewRows() - 2) + 1 = viewRows()
 *   ⇒ scrollable() = (total > viewRows())   【结构上永不为真】
 *   ```
 *
 * 也就是说：滚轮 / 拖拽 / 滚动条 / "还能往下滚"方向提示这四样**全都写好了**
 * 却**永远走不到**，超长说明只是被 `maxLines` **静默截断**。
 *
 * 现在 `maxLines` **只由 `DESC_MAX_LINES` 决定**（不再跟着一屏几行走），
 * 所以"内容比一屏高"真的会发生 —— 那四样开始工作。
 */

/**
 * 说明最多折几行（同时也是 `SkillDetail` 里 `Text` 池子的槽位数）。
 *
 * ==================================================================
 * ⚠️ 它现在是**唯一的**折行上限（"极大但有限"）
 * ==================================================================
 *
 * 上限本身要留：`wrapText` 的每一行要做一次二分（每步一次文本测量），
 * 而说明每换一个技能都要折一遍；这个数还同时是 `Text` 对象的个数
 * （那些对象**一次建好、之后只改字**，不重建 —— 见 `primitives.Label`）。
 *
 * ⚠️ 但它**不许**再和"一屏放得下几行"挂钩（那正是上面那段说的那个 bug）。
 * 24 行 ≈ 700 字（400px 宽、11px 字号下一行约 30 字），远超当前任何一条
 * 真实说明 —— 所以现实中不会撞到它，而真要撞到也只是"折到 24 行为止"。
 */
export const DESC_MAX_LINES = 24;

/**
 * **内容行 `row` 在不在可视窗口里**。
 *
 * @param row    内容里的行号（0 = 名字，1..N = 说明，N+1 = 代价）
 * @param offset 第一条可见的内容行（= `SkillDetail.offset`）
 * @param rows   一屏放得下几行（= `SkillDetail.viewRows()`）
 *
 * ⚠️ 这是**上半开区间**（`[offset, offset + rows)`）：第 `offset + rows`
 * 行的上沿正好落在可视底边**之外**，算它可见就会画出区外。
 *
 * ⚠️ 为什么必须有它：`content` 容器靠 `y` 上移实现滚动，而 `Text` 池是
 * **内容行**的槽位（第 i 槽放第 i 行）。内容比一屏高之后，窗口外的那些行
 * 会被画到详情区**外面**（本仓库的 Pixi 遮罩在 headless 下不生效，
 * 见 `./wrapText`）—— 所以裁剪只能自己做，判据就是本函数。
 */
export function contentRowVisible(row: number, offset: number, rows: number): boolean {
  return row >= offset && row < offset + rows;
}
