/**
 * 技能格内三个标签的位置：**技能字 / 冷却秒数 / 按键提示**。
 *
 * ------------------------------------------------------------------
 * 为什么把这三个坐标抽成函数
 * ------------------------------------------------------------------
 *
 * 它们互相挤，而且**挤出去会被画布边缘裁掉** —— 而画布是固定
 * 960×540、不随窗口变化，所以这类错误在截图里很难发现
 * （看起来像"字没画"而不是"画到外面了"）。
 *
 * 实际踩过的坑：
 *   1. 冷却数字放正中 → 与技能字**完全重叠**
 *   2. 按键提示移到格子**外面**下方避开冷却弧 → 落到 y=531，
 *      而画布只有 540，被**截断**
 *   3. 冷却数字又放底部居中 → 与右下角的按键提示挤在一起
 *
 * 抽出来之后可以在 node 里断言"三个标签都在格子内、互不重叠"，
 * 不必靠截图肉眼判断。
 */
export interface SlotLabelRects {
  readonly glyph: { readonly x: number; readonly y: number };
  readonly cooldown: { readonly x: number; readonly y: number };
  readonly key: { readonly x: number; readonly y: number };
}

export function skillSlotLabels(rect: {
  readonly x: number;
  readonly y: number;
  readonly w: number;
  readonly h: number;
}): SlotLabelRects {
  return {
    /**
     * 技能字：水平居中，**偏上**。
     *
     * 44px 的格子放不下"26px 的楷体字 + 13px 的秒数"而不重叠 ——
     * 这一点是被矩形重叠检测算出来的（我肉眼调了三轮都没定下来）。
     * 所以字缩到 18px 并偏上，给下方的秒数让出 20px 净空。
     */
    glyph: { x: rect.x + rect.w / 2, y: rect.y + 2 },
    /**
     * 冷却秒数：水平居中，压在技能字下方。
     *
     * 居中而不是塞角落：秒数是冷却时最需要读的信息，
     * 而字此刻是"已知的那个技能"，让位给数字更合理。
     */
    cooldown: { x: rect.x + rect.w / 2, y: rect.y + rect.h - 22 },
    /**
     * 按键提示：**左上角**。
     *
     * 位置换过三次：
     *   1. 格子内右下角 → 被冷却弧压住
     *   2. 格子**外**下方 → 落到画布底边之外被截断
     *   3. 格子内右下角（弧缩小之后）→ 与冷却数字挤在一起
     *
     * 左上角是唯一的空位：冷却弧的内圈在那里留了空白，
     * 而技能字在正中、数字在正中下方，三者互不侵犯。
     */
    key: { x: rect.x + 3, y: rect.y + 2 },
  };
}
