/**
 * 技能格内三个标签的位置：**技能字 / 冷却秒数 / 按键提示**。
 *
 * ------------------------------------------------------------------
 * 为什么把这三个坐标抽成函数
 * ------------------------------------------------------------------
 *
 * 它们互相挤，而且**挤出去会被画布边缘裁掉** —— 而画布是固定
 * 960×540、不随窗口变化，所以这类错误在截图里很难发现
 * （看起来像"字没画"而不是"画到外面了"）。
 *
 * 实际踩过的坑：
 *   1. 冷却数字放正中 → 与技能字**完全重叠**
 *   2. 按键提示移到格子**外面**下方避开冷却弧 → 落到 y=531，
 *      而画布只有 540，被**截断**
 *   3. 冷却数字又放底部居中 → 与右下角的按键提示挤在一起
 *
 * 抽出来之后可以在 node 里断言"三个标签都在格子内、互不重叠"，
 * 不必靠截图肉眼判断。
 */
export interface SlotLabelRects {
  /** 资源代价（右下角，右对齐） */
  readonly cost: { readonly x: number; readonly y: number };
  /** 技能的固有冷却（左下角，左对齐） */
  readonly skillCd: { readonly x: number; readonly y: number };
  readonly glyph: { readonly x: number; readonly y: number };
  readonly cooldown: { readonly x: number; readonly y: number };
  readonly key: { readonly x: number; readonly y: number };
}

/**
 * 技能字纵向的光学补偿（像素）。
 *
 * 见 `skillSlotLabels` 里对 `glyph` 的说明 —— 这个数不是调到手感对为止，
 * 是由"行框高 28 / 字形高 20.5、重心偏下"算出来再实测校准的。
 */
export const GLYPH_NUDGE = 4;

export function skillSlotLabels(rect: {
  readonly x: number;
  readonly y: number;
  readonly w: number;
  readonly h: number;
}): SlotLabelRects {
  return {
    /**
     * 技能字（图标）：水平正中 + **光学居中**。
     *
     * ⚠️ 纵向必须减去 `GLYPH_NUDGE`。
     *
     * 我一度把它删了（理由："四角都占满了，图标必须老实居中"）——
     * 那是错的。Pixi 的 `Text` 是按**整行高**居中的，而 CJK 字形的
     * 重心明显低于行框中心：26px 的楷体，行框 28px 而字形只有约 20.5px，
     * 且偏下。所以"数学居中"看起来就是**坐得太低**。
     *
     * 实测（26px 楷体、40px 格子）：按行框居中时字形落在
     * y 498..526（格子 492..532），下边缘几乎贴底；
     * 上移 `GLYPH_NUDGE` 之后才是视觉居中。
     */
    glyph: { x: rect.x + rect.w / 2, y: rect.y + rect.h / 2 - GLYPH_NUDGE },
    /**
     * **实时**冷却秒数：格子**正中**。
     *
     * 需求："实时 cd 还是保持在原来的中间"。
     *
     * 它盖在图标上（先例：26px 数字压 26px 图标，靠描边保证可读），
     * 读条/冷却这类"正在发生"的信息最值得占中心位。
     * 锚点 (0.5, 0.5)，所以这里给的是中心点。
     */
    cooldown: { x: rect.x + rect.w / 2, y: rect.y + rect.h / 2 },
    /**
     * **固有**冷却（技能本身多长的 CD）：左下角，右对齐到底边左角。
     *
     * 需求："左下 我说的是技能的固有 cd 时间" —— 与实时剩余是两回事。
     * 它是个**静态**数字，所以放在角上不抢中心。
     */
    skillCd: { x: rect.x + 3, y: rect.y + rect.h - 3 },
    /** 按键提示：左上角（锚点 0,0） */
    key: { x: rect.x + 3, y: rect.y + 2 },
    /**
     * 资源代价：**左下偏右**（与固有 CD 同一行，右对齐）。
     *
     * 30px 的格子角落放不下"30 / 5s"两件事挤在一侧，
     * 所以代价贴右边、固有 CD 贴左边，共用底部那一行（锚点 1,1）。
     */
    cost: { x: rect.x + rect.w - 3, y: rect.y + rect.h - 3 },
  };
}

