/**
 * **对话头像表**：出战单位的 id → `public/fd2/portraits/` 里的一张脸。
 *
 * ==================================================================
 * 它是什么（一句话，没有"和"）
 * ==================================================================
 *
 * 它是"谁用哪张对话头像"的**唯一**声明 —— 备战屏卡片上那颗小头像与
 * 右侧详情区的大头像读的都是它，两处不可能画成两个人。
 *
 * ==================================================================
 * 配对：索爾 / 凱麗 / 索菲亞 → 林晚风 / 凯丽 / 黛玄
 * ==================================================================
 *
 * 素材方的名字**不是我猜的**：`public/fd2/INDEX.html` 的
 * 「对话头像（portraits）」表里逐条写着 `alt="索爾"` / `alt="凱麗"` /
 * `alt="索菲亞"`，并各带一句身份（`可玩 · 劍士 Lv1` / `可玩 · 武者 Lv10` /
 * `可玩 · 僧侶 Lv16`）。
 *
 * | 我们的角色 | 素材编号 | 素材方的名字 | 依据 |
 * |---|---|---|---|
 * | 林晚风（男 · 剑士型 · 主视角） | `DATO_000` | 索爾 | 素材里唯一的**男主**，`可玩 · 劍士`；我们的林晚风也是剑士型主视角 |
 * | 凯丽 | `DATO_012` | 凱麗 | **名字逐字相同**（简繁差异），性别、定位都不用推 |
 * | 黛玄 | `DATO_011` | 索菲亞 | 剩下的一位女性 `可玩 · 僧侶`；黛玄是三人里偏法系/辅助的那个 |
 *
 * ⚠️ **那三个名字（素材方的）只出现在上面这段注释里，不以字符串形式进
 * 代码** —— 渲染层不许硬编码中文文案（eslint `raid/i18n/no-hardcoded-cjk`
 * 会拦，AGENTS.md §2 的 I1）。它们的作用是"让配对**可复核**"，而复核走
 * 测试（见下）。
 *
 * ⚠️ **林晚风与黛玄这两条是"我判断的"**（用户没指定）：
 * 依据是**性别 + 素材自带的定位**，而不是"剩下哪个就配哪个"。
 *
 * ⚠️ 这张表**不改变任何 id**（`player` / `kaili` / `daixuan` 是存档键，
 * 见 `data/roster.ts`）—— 它只回答"画哪张脸"。
 *
 * ⚠️ 与 `render/spriteAssets.ts` 是**两套素材**（那边是战斗立绘帧
 * `rgba/<slot>/`，这里是对话头像）：所以不能去那边"顺便"加一个字段。
 * 但两边的**配对必须一致**—— `tests/unit/preparePortraits.test.ts`
 * 有一条断言盯着这件事（否则会出现"战斗里是凯丽、卡片上是索菲亚"）。
 *
 * ⚠️ 这一轮的形状教训（我犯过两次）：**搬走一个导出、或新建一个模块时，
 * 必须 grep 出全部消费者**。`PREPARE_LAYOUT` 搬去 `prepareLayout.ts` 时
 * 漏了 `characterSelectLogic`，而本文件的 `../portraitAssets` 少了一层
 * 前缀 —— 两处都让页面**整片白屏**，而 typecheck 只抓到第一处
 * （Vite 的模块解析与 tsc 不完全一样：路径写错 tsc 会报，但**运行时**
 * 才白屏的顺序是先撞到哪一个不一定）。
 *
 * ==================================================================
 * ⚠️ 帧：用 `_m0`
 * ==================================================================
 *
 * 每个角色有 4 张嘴型帧（`_m0.._m3`，见 INDEX.html 的说明）。备战屏是
 * **静止的一屏**，没有对话在播 —— 所以取 `_m0`（INDEX.html 自己那张表
 * 取的也是 `_m0`，即"闭嘴/中性的那一帧"）。
 * ⚠️ 不要为了"看起来在说话"而每帧换 m0..m3：那是**没有对话的动画**，
 * 只会让卡片闪。
 */

import { assetUrl } from './assetUrl';

/** 一个单位的对话头像。 */
export interface PortraitAsset {
  /** 出战单位的 id（`data/roster.ts` 的 `RosterEntry.id`）。 */
  readonly id: string;
  /**
   * 素材里的编号（`public/fd2/portraits/DATO_<n>_m0.png`）。
   *
   * ⚠️ 数字前面补零到 3 位（`000` / `011` / `012`），与文件名逐字一致。
   */
  readonly number: string;
}

/**
 * 素材原始边长（正方形）。
 *
 * ⚠️ 写死它（而不是等图加载完再读）：详情区 / 卡片的高度**在布局表里
 * 已经定死**（`portraitBox`），若把缩放比拖到"图片加载完才知道"，画面
 * 会在加载完成的一瞬间跳一下。所以缩放比按这个**已知常量**算，加载
 * 失败只是**不显示**（占位由调用方画）。
 *
 * 真值核对在 `tests/unit/preparePortraits.test.ts`（读 PNG 文件头）。
 */
export const PORTRAIT_PIXELS = 80;

/** 出战单位 → 对话头像。顺序与 `data/roster.ts` 的人物名单一致。 */
export const PORTRAITS: readonly PortraitAsset[] = [
  /**
   * 林晚风 ← 索爾（`可玩 · 劍士 Lv1`，素材里唯一的男主）。
   *
   * ⚠️ 战斗立绘用的是同一个 slot（`spriteAssets` 的 `player-linwanfeng`
   * 就是索爾那一套）—— 两张脸本来就是同一个人。
   */
  { id: 'player', number: '000' },
  /** 凯丽 ← 凱麗（`可玩 · 武者 Lv10`，同名同性别）。 */
  { id: 'kaili', number: '012' },
  /** 黛玄 ← 索菲亞（`可玩 · 僧侶 Lv16`，三位可玩女性里偏辅助的那个）。 */
  { id: 'daixuan', number: '011' },
];

/** 某个单位的对话头像（没有就 `undefined` —— 调用方画占位）。 */
export function portraitFor(id: string): PortraitAsset | undefined {
  return PORTRAITS.find((p) => p.id === id);
}

/** 一张对话头像的 URL（`public/fd2/portraits/DATO_000_m0.png`）。 */
export function portraitUrl(asset: PortraitAsset): string {
  return assetUrl(`fd2/portraits/DATO_${asset.number}_m0.png`);
}
