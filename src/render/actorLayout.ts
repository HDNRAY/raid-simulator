/**
 * 角色的**渲染布局常量**。
 *
 * 抽出来的原因：这些值原先散在 `BattleScene.ts` 里，而拆分后的
 * 部件（`parts/playerActor.ts`）也要用 —— 留在主模块就会形成
 * "部件反向 import 场景"的环。
 */

/**
 * 闪避位移的峰值（逻辑像素）。**负 = 向左**。
 *
 * 演进 26 → 52（需求："幅度按现在的翻倍"）→ **-52**。
 *
 * ⚠️ 符号变了，因为**站位互换了**（需求："boss在右…位置互换一下"）：
 * 现在**玩家在右（x 630）、Boss 在左（x 300）**，所以"躲开"是**向左**，
 * 与旧版正好相反。幅度不变。
 *
 * 本体宽约 108（cx±54），左移 52 后左缘到 524 —— 与 Boss（约 x 300）
 * 之间仍有 200px 余量，不会撞上。
 */
export const DODGE_PEAK_X = -52;

/**
 * 战斗双方的**站位**（脚底中心，逻辑坐标）。
 *
 * ==================================================================
 * ⚠️ 为什么放在这里而不是写在 `BattleScene.ts` 的字面量里
 * ==================================================================
 *
 * 1. **这是布局知识**，与 `DODGE_PEAK_X` 是同一类东西 —— 而闪避幅度
 *    的推算正是**基于这两个 x**（"左移之后离对面还有多少余量"）。
 *    分开放就会出现"改了一处、另一处的注释还在说旧数字"。
 * 2. `BattleScene.ts` 已经贴着 700 行上限（AGENTS.md §3），而把坐标
 *    搬到这里是**横向切割**，不是压缩注释。
 *
 * ⚠️ **站位在某个版本互换过**（需求："boss在右，位置互换一下"）：
 * 现在**玩家在右（630）、Boss 在左（300）**，与旧版正好相反。
 * 互换必须连**朝向**一起翻（见 `ActorSprite` 的 `facing`）——
 * 否则两人会背对背。
 *
 * ⚠️ `y` 两边**不一样**（Boss 378 / 玩家 456）：这是各自的地面线，
 * 与横向站位无关，互换时**不动**。
 */
export const ACTOR_POS = {
  /** Boss：偏左。 */
  boss: { x: 300, y: 378 },
  /** 玩家：偏右。与 `playerActor` 的 `PLAYER_CX` 是同一个数。 */
  player: { x: 630, y: 456 },
} as const;

/**
 * 飘字的**高度**（逻辑坐标），按角色分开。
 *
 * ==================================================================
 * 只有 `x` 是"站位知识"，`y` 是"美术留白"，所以它们来源不同
 * ==================================================================
 *
 * `x` **必须**跟着站位走（"飘字落在被打的那个人头上"）—— 所以它只能
 * 从 `ACTOR_POS` 派生，见 `floatAnchorOf`。而 `y` 取决于**那个角色
 * 头顶上方还有多少空地**，两个角色完全不同：
 *
 *   | 角色 | 脚底 y | 头顶（≈140 高的形象） | 头顶上方的空带 | 飘字 y |
 *   |---|---|---|---|---|
 *   | Boss 傲慢 | 378 | ≈ 205 | 顶栏底 106 .. 头顶 205 | **150** |
 *   | 玩家林晚风 | 456 | ≈ 270 | 顶栏底 106 .. 头顶 270 | **408** |
 *
 * ⚠️ 这两个值**不是这次改的**（2026-10-13 的 bug 只在 `x` 上）：它们
 * 此刻是实机的样子，Boss 那条落在火焰状头发**上方**、玩家那条落在
 * 石头铠甲**下方**的腿部空处。
 *
 * ⚠️ 我一度把两个角色合并成一个共用高度（`FLOAT_TEXT_Y = 250`）想"少
 * 一份真相"，**截图证明那是错的**：250 正好压在傲慢的头发/脸上
 * （它的头顶只到约 205，250 是它的上身）。教训是"能合并"不等于"该
 * 合并"—— 这两个数描述的是两个不同的空带，不是同一个事实的两份。
 *
 * ⚠️ 键是**角色 id**（与 `ACTOR_POS` 的语义一致）。写成 `as const` 而不是
 * `Record<string, number>`：后者在这套 `tsconfig` 下取出来是
 * `number | undefined`，于是 `floatAnchorOf` 得再补一层兜底分支 ——
 * 那正是"第二套 if 分支"的味道（AGENTS.md 禁止）。现在只有两个键，
 * 由 `floatAnchorOf` 显式选一个。
 */
export const FLOAT_TEXT_Y = {
  player: 408,
  boss: 150,
} as const;

/**
 * 某个角色挨打 / 回血 / 受击闪避时，飘字应该出现在哪。
 *
 * ⚠️ **这是飘字锚点的唯一真相**：渲染层（`ViewAdapter`）不许再自己写
 * `630` / `300` 这样的数字。2026-10-13 的 bug 正是"两处各算一遍" ——
 * 站位互换时 `ACTOR_POS` 改了，而 `viewAdapter` 里的字面量没跟着改，
 * 于是**玩家的飘字跑到 Boss 头上、Boss 的飘字跑到玩家头上**。
 *
 * 参数用 `string`（事件里的 `targetId` 类型）。判据是
 * `targetId === 'player'` —— 与 `viewAdapter` 里 `onBoss` 的判据**同源**：
 * 全场只有玩家在右、Boss 在左，所以"不是玩家"与"是 Boss"是同一件事。
 * 不能反过来写，否则未知 id 会被送到玩家那一侧。
 */
export function floatAnchorOf(targetId: string): { readonly x: number; readonly y: number } {
  const isPlayer = targetId === 'player';
  return {
    x: isPlayer ? ACTOR_POS.player.x : ACTOR_POS.boss.x,
    y: isPlayer ? FLOAT_TEXT_Y.player : FLOAT_TEXT_Y.boss,
  };
}

